package ch09.erasure;

import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.function.Supplier;

public class Erasure {

    static class Node<T extends Comparable<T>> implements Comparable<Node<T>> {
        T value;
        Node(T value) { this.value = value; }
        public int compareTo(Node<T> o) { return value.compareTo(o.value); }
    }

    // Can't write `new T()`: pass a factory (Supplier) or a Class<T> token instead
    static <T> List<T> fill(int n, Supplier<T> factory) {
        List<T> out = new ArrayList<>();
        for (int i = 0; i < n; i++) out.add(factory.get());
        return out;
    }

    static <T> T create(Class<T> type) throws ReflectiveOperationException {
        return type.getDeclaredConstructor().newInstance();
    }

    // Can't write `new T[n]`: use Class<T> + java.lang.reflect.Array, or use a List
    @SuppressWarnings("unchecked")
    static <T> T[] newArray(Class<T> type, int n) {
        return (T[]) java.lang.reflect.Array.newInstance(type, n);
    }

    // Generic varargs create a T[] -> "possible heap pollution" unless proven safe
    @SafeVarargs
    static <T> List<T> listOf(T... items) { return new ArrayList<>(Arrays.asList(items)); }

    // Heap pollution demo: returning a generic varargs array is NOT safe
    static <T> T[] toArray(T... items) { return items; }                   // Object[] at run time when T is erased
    static <T> T[] pickTwo(T a, T b) { return toArray(a, b); }

    public static void main(String[] args) throws Exception {
        List<String> strings = new ArrayList<>();
        List<Integer> ints = new ArrayList<>();
        System.out.println("same runtime class? " + (strings.getClass() == ints.getClass())
                + " -> " + strings.getClass().getName());

        Object o = strings;
        System.out.println("o instanceof List<?>: " + (o instanceof List<?>));
        // o instanceof List<String>             // compile error (not reifiable) - except when the compiler can prove it safe

        System.out.println("fill: " + fill(3, StringBuilder::new).size() + " builders, create: \"" + create(String.class) + "\"");
        String[] arr = newArray(String.class, 2);
        System.out.println("newArray component type: " + arr.getClass().getComponentType().getSimpleName() + "[" + arr.length + "]");
        System.out.println("listOf: " + listOf("a", "b"));

        // Bridge method generated by the compiler for Node.compareTo
        for (Method m : Node.class.getDeclaredMethods()) {
            if (m.getName().equals("compareTo")) {
                System.out.println("compareTo(" + m.getParameterTypes()[0].getSimpleName() + ") bridge=" + m.isBridge());
            }
        }

        // Unchecked cast: no error at the cast, failure appears later, far away
        List<Object> objs = new ArrayList<>(List.of("text"));
        @SuppressWarnings("unchecked")
        List<Integer> lie = (List<Integer>) (List<?>) objs;   // compiles with a warning, no check at run time
        try {
            Integer n = lie.get(0);                             // the compiler inserted a cast here
            System.out.println(n);
        } catch (ClassCastException e) {
            System.out.println("heap pollution -> ClassCastException on read");
        }

        try {
            String[] two = pickTwo("x", "y");                   // toArray created an Object[], not String[]
            System.out.println(two.length);
        } catch (ClassCastException e) {
            System.out.println("pickTwo -> ClassCastException: generic varargs array escaped");
        }
    }
}
