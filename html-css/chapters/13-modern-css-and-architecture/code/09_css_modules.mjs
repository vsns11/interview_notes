// CSS Modules, for real: Lightning CSS (the CSS compiler used by Vite, Parcel, ...) compiles
// 09_card.module.css into (1) scoped CSS and (2) a JS object mapping the names you wrote to generated names.
import { transform } from 'lightningcss';
import fs from 'node:fs';

const { code, exports } = transform({
  filename: '09_card.module.css',
  code: fs.readFileSync('09_card.module.css'),
  cssModules: { pattern: '[local]_[hash]' },
});
const styles = Object.fromEntries(Object.entries(exports).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) =>
  [k, [v.name, ...v.composes.map(c => c.name)].join(' ')]));
console.log('import styles from "./card.module.css"  ->  styles =', styles);
console.log('\nGenerated CSS (first rules):\n' + code.toString().split('\n').slice(0, 12).join('\n'));

// What a component would render: className={styles.card}
const card = (cls, name, price) => `<article class="${cls}">
  <h3 class="${styles.title}">${name}</h3><p class="${styles.price}">${price}</p>
  <button class="${styles.button}">Add to cart</button></article>`;
fs.writeFileSync('09_css_modules.out.css', code);
fs.writeFileSync('09_css_modules.html', `<!doctype html><html lang="en"><meta charset="utf-8"><title>Card — CSS Modules</title>
<!-- generated by 09_css_modules.mjs -->
<link rel="stylesheet" href="09_css_modules.out.css">
<body>${card(styles.card, 'Trail shoes', '$89')}${card(styles.featured, 'Rain jacket', '$129')}</body></html>\n`);
console.log('\nwrote 09_css_modules.out.css and 09_css_modules.html');
