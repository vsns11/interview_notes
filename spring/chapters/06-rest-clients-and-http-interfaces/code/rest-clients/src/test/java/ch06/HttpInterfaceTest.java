package ch06;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import ch06.client.BookDto;
import ch06.client.CatalogApi;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.ResponseEntity;
import org.springframework.web.client.HttpClientErrorException;
import org.springframework.web.client.RestClient;
import org.springframework.web.client.support.RestClientAdapter;
import org.springframework.web.service.invoker.HttpServiceProxyFactory;

class HttpInterfaceTest extends LiveServerTest {

    @Autowired CatalogApi catalogApi;     // generated by @ImportHttpServices + Boot auto-config

    @Test
    void callsThroughTheInterface() {
        System.out.println("bean class     -> " + catalogApi.getClass().getSimpleName().replaceAll("\\d+$", "N"));
        BookDto one = catalogApi.get(1);
        System.out.println("get(1)         -> " + one);
        System.out.println("byAuthor(...)  -> " + catalogApi.byAuthor("Martin Fowler"));
        ResponseEntity<BookDto> e = catalogApi.getEntity(2);
        System.out.println("getEntity(2)   -> " + e.getStatusCode()
                + " server saw X-Client=" + e.getHeaders().getFirst("X-Seen-Client"));
        ResponseEntity<BookDto> created = catalogApi.create(new BookDto(null, "Accelerate", "Nicole Forsgren"));
        System.out.println("create(...)    -> " + created.getStatusCode() + " " + created.getBody());
        System.out.println("greetingV2()   -> " + catalogApi.greetingV2());

        assertThat(one.author()).isEqualTo("Michael T. Nygard");
        assertThat(e.getHeaders().getFirst("X-Seen-Client")).isEqualTo("handbook-ch06");   // from properties
        assertThat(catalogApi.greetingV2()).isEqualTo("v2: hello");
    }

    @Test
    void errorsAreTheSameExceptionsAsRestClient() {
        assertThatThrownBy(() -> catalogApi.get(999))
                .isInstanceOf(HttpClientErrorException.NotFound.class)
                .satisfies(ex -> System.out.println("get(999)       -> " + ex.getClass().getSimpleName()));
    }

    @Test
    void buildingTheProxyByHand() {
        // What Boot does for you: RestClient -> adapter -> proxy factory -> client
        RestClient restClient = RestClient.builder().baseUrl(baseUrl()).build();
        HttpServiceProxyFactory factory = HttpServiceProxyFactory
                .builderFor(RestClientAdapter.create(restClient)).build();
        CatalogApi manual = factory.createClient(CatalogApi.class);
        System.out.println("manual proxy get(3) -> " + manual.get(3).title());
        assertThat(manual.get(3).id()).isEqualTo(3L);
    }
}
