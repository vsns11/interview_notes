CREATE TABLE customer (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100) NOT NULL,
    email VARCHAR(200) NOT NULL
);

CREATE TABLE product (                 -- natural key: the SKU is assigned by us, not generated
    sku   VARCHAR(20) PRIMARY KEY,
    name  VARCHAR(100) NOT NULL,
    price DECIMAL(10, 2) NOT NULL
);

CREATE TABLE purchase_order (          -- aggregate root
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      INT NOT NULL,
    customer_id  BIGINT NOT NULL REFERENCES customer (id),   -- reference to ANOTHER aggregate: just an id
    status       VARCHAR(20) NOT NULL,
    ship_street  VARCHAR(100),         -- embedded value object Address (prefix ship_)
    ship_city    VARCHAR(50),
    created_at   TIMESTAMP
);

CREATE TABLE order_line (              -- part of the order aggregate, no id of its own
    purchase_order_id BIGINT NOT NULL REFERENCES purchase_order (id),
    line_no           INT    NOT NULL, -- list index
    sku               VARCHAR(20) NOT NULL,
    quantity          INT    NOT NULL,
    unit_price        DECIMAL(10, 2) NOT NULL,
    PRIMARY KEY (purchase_order_id, line_no)
);
