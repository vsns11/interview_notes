-- 9.8  INSERT
\pset null '(null)'
CREATE TABLE contacts (
    contact_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  text NOT NULL,
    last_name   text NOT NULL,
    age         integer CHECK (age >= 0),
    city        text DEFAULT 'Pune',
    created_at  timestamp NOT NULL DEFAULT '2025-06-01 09:00'
);

-- Always name the columns; unnamed ones get their DEFAULT (or NULL)
INSERT INTO contacts (first_name, last_name, age) VALUES ('Tara', 'Mendes', 28);

-- Several rows in one statement
INSERT INTO contacts (first_name, last_name, age, city) VALUES
    ('Omar', 'Mendes', 31, 'Mumbai'),
    ('Yuki', 'Tanaka', NULL, DEFAULT);          -- DEFAULT keyword inside VALUES

-- Without a column list you must supply every column, in table order
INSERT INTO contacts VALUES (DEFAULT, 'Leo', 'Brandt', 40, 'Delhi', '2025-06-02 10:00');

-- RETURNING gives back generated values (no second query needed)
INSERT INTO contacts (first_name, last_name) VALUES ('Ines', 'Silva')
RETURNING contact_id, city, created_at;

-- INSERT ... SELECT copies rows from a query
INSERT INTO contacts (first_name, last_name, city)
SELECT first_name, last_name, city FROM customers WHERE country = 'UK'
RETURNING contact_id, first_name, city;

SELECT * FROM contacts ORDER BY contact_id;

\set ON_ERROR_STOP 0
-- Double quotes mean an identifier (column name) in standard SQL, not a string
INSERT INTO contacts (first_name, last_name) VALUES ("Ana", "Lima");
-- Too many values for the listed columns
INSERT INTO contacts (first_name, last_name) VALUES ('Ana', 'Lima', 22);
-- Constraint violations stop the whole statement: no row of this multi-row insert is kept
INSERT INTO contacts (first_name, last_name, age) VALUES ('Ok', 'Row', 20), ('Bad', 'Row', -1);
\set ON_ERROR_STOP 1
SELECT count(*) AS still_7 FROM contacts;
